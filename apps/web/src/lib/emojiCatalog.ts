/**
 * Accents off, lowercase.
 *
 * Somebody typing "arbol" in a hurry should find the tree, and somebody typing
 * "árbol" properly should find it too. Normalising both sides is the only way
 * both work, and it is cheaper than writing every keyword twice.
 */
export function foldText(input: string): string {
  return input
    .toLowerCase()
    .normalize("NFD")
    .replace(/[̀-ͯ]/g, "");
}
