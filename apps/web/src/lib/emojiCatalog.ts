/**
 * The emoji this app offers, and the words that find them.
 *
 * Bundled rather than fetched: panel pages run under a CSP that allows no
 * external assets, and an emoji picker that needs a CDN is a picker that
 * breaks on exactly the pages that are shared with other people. It is also
 * why this is a curated list and not the whole of Unicode — the full set is
 * fifteen hundred entries whose keywords would have to be translated to be
 * findable, and a picker where "casa" finds nothing is worse than a shorter
 * one where it finds the house.
 *
 * Keywords are Spanish, lowercase and unaccented, because the search strips
 * accents before comparing: somebody typing "arbol" in a hurry should find the
 * tree. A few English words are kept where they are what people actually type
 * ("ok", "wifi", "email").
 */

export interface EmojiEntry {
  /** The character itself. */
  e: string;
  /** Space-separated search words. The first one is used as the tooltip. */
  k: string;
}

export interface EmojiCategory {
  /** Stable id, used by the tabs and by the i18n key. */
  id: string;
  /** One character, shown on the tab: a row of words would not fit. */
  tab: string;
  items: EmojiEntry[];
}

